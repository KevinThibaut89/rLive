//! The MIDI-style messages that travel through tracks and devices.

/// Identifies one sounding note, so a note-off or expression reaches it even when another
/// note shares its key. Zero means unassigned, as with notes parsed from plain MIDI.
pub type NoteId = u32;

/// Pitch bend range of an MPE member channel, in semitones either way.
pub const MPE_BEND_RANGE: f32 = 48.0;

/// The controller MPE uses for slide.
pub const SLIDE_CC: u8 = 74;

/// Who allocated a [`NoteId`]. Sources that feed the same track take different spaces, so
/// their ids can never collide.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NoteSpace {
    Session = 1,
    Arrangement = 2,
    MidiInput = 3,
    /// Notes generated by devices (MIDI effects and the like).
    Device = 4,
}

/// Hands out [`NoteId`]s within one [`NoteSpace`]. Ids stay below 2^31, so they fit the signed
/// note ids of CLAP and VST3, and are never zero because the space sits in the high bits.
#[derive(Debug, Clone, Copy)]
pub struct NoteIds {
    space: u32,
    next: u32,
}

impl NoteIds {
    const COUNTER_MASK: u32 = 0x0fff_ffff;

    pub const fn new(space: NoteSpace) -> Self {
        Self {
            space: (space as u32) << 28,
            next: 0,
        }
    }

    pub fn alloc(&mut self) -> NoteId {
        let id = self.space | self.next;
        self.next = (self.next + 1) & Self::COUNTER_MASK;
        id
    }
}

/// The dimensions of per-note expression.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ExprKind {
    /// Semitones relative to the note's key.
    Pitch,
    /// 0..1, MPE's Y axis (CC74).
    Slide,
    /// 0..1, poly aftertouch or MPE pressure.
    Pressure,
}

/// A MIDI-style message. Velocities are normalised to `0.0..=1.0`.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum MidiMessage {
    NoteOn {
        channel: u8,
        key: u8,
        velocity: f32,
        note_id: NoteId,
        /// Offset in semitones. A tuning source must also add this to [`ExprKind::Pitch`]
        /// values, since plugin formats have a single tuning dimension.
        tuning: f32,
    },
    NoteOff {
        channel: u8,
        key: u8,
        velocity: f32,
        note_id: NoteId,
    },
    /// A change to one note's expression. See [`ExprKind`] for the value range of each kind.
    NoteExpr {
        channel: u8,
        key: u8,
        note_id: NoteId,
        kind: ExprKind,
        value: f32,
    },
    ControlChange {
        channel: u8,
        cc: u8,
        value: u8,
    },
    /// Pitch bend in the range -1.0..=1.0.
    PitchBend {
        channel: u8,
        value: f32,
    },
    /// Monophonic aftertouch, 0..1.
    ChannelPressure {
        channel: u8,
        value: f32,
    },
    ProgramChange {
        channel: u8,
        program: u8,
    },
    AllNotesOff,
}

impl MidiMessage {
    /// Put this message on another channel. `AllNotesOff` has none to change.
    pub fn set_channel(&mut self, new: u8) {
        match self {
            Self::NoteOn { channel, .. }
            | Self::NoteOff { channel, .. }
            | Self::NoteExpr { channel, .. }
            | Self::ControlChange { channel, .. }
            | Self::PitchBend { channel, .. }
            | Self::ChannelPressure { channel, .. }
            | Self::ProgramChange { channel, .. } => *channel = new,
            Self::AllNotesOff => {}
        }
    }

    /// Parse a raw MIDI 1.0 message (as delivered by `midir`).
    pub fn from_bytes(bytes: &[u8]) -> Option<Self> {
        let status = *bytes.first()?;
        let channel = status & 0x0f;
        match status & 0xf0 {
            0x80 => Some(Self::NoteOff {
                channel,
                key: *bytes.get(1)? & 0x7f,
                velocity: (*bytes.get(2).unwrap_or(&64) & 0x7f) as f32 / 127.0,
                note_id: 0,
            }),
            0x90 => {
                let key = *bytes.get(1)? & 0x7f;
                let vel = *bytes.get(2)? & 0x7f;
                if vel == 0 {
                    Some(Self::NoteOff {
                        channel,
                        key,
                        velocity: 0.5,
                        note_id: 0,
                    })
                } else {
                    Some(Self::NoteOn {
                        channel,
                        key,
                        velocity: vel as f32 / 127.0,
                        note_id: 0,
                        tuning: 0.0,
                    })
                }
            }
            0xa0 => Some(Self::NoteExpr {
                channel,
                key: *bytes.get(1)? & 0x7f,
                note_id: 0,
                kind: ExprKind::Pressure,
                value: (*bytes.get(2)? & 0x7f) as f32 / 127.0,
            }),
            0xb0 => {
                let cc = *bytes.get(1)? & 0x7f;
                let value = *bytes.get(2)? & 0x7f;
                if cc == 123 {
                    Some(Self::AllNotesOff)
                } else {
                    Some(Self::ControlChange { channel, cc, value })
                }
            }
            0xc0 => Some(Self::ProgramChange {
                channel,
                program: *bytes.get(1)? & 0x7f,
            }),
            0xd0 => Some(Self::ChannelPressure {
                channel,
                value: (*bytes.get(1)? & 0x7f) as f32 / 127.0,
            }),
            0xe0 => {
                let lsb = (*bytes.get(1)? & 0x7f) as i32;
                let msb = (*bytes.get(2)? & 0x7f) as i32;
                let raw = (msb << 7 | lsb) - 8192;
                Some(Self::PitchBend {
                    channel,
                    value: raw as f32 / 8192.0,
                })
            }
            _ => None,
        }
    }

    /// Encode as raw MIDI 1.0 bytes. Returns the bytes and the number used.
    pub fn to_bytes(&self) -> ([u8; 3], usize) {
        match *self {
            Self::NoteOn {
                channel,
                key,
                velocity,
                ..
            } => (
                [
                    0x90 | (channel & 0x0f),
                    key & 0x7f,
                    ((velocity * 127.0).round() as u8).clamp(1, 127),
                ],
                3,
            ),
            Self::NoteOff {
                channel,
                key,
                velocity,
                ..
            } => (
                [
                    0x80 | (channel & 0x0f),
                    key & 0x7f,
                    ((velocity * 127.0).round() as u8).min(127),
                ],
                3,
            ),
            Self::NoteExpr {
                channel,
                key,
                kind,
                value,
                ..
            } => match kind {
                ExprKind::Pressure => ([0xa0 | (channel & 0x0f), key & 0x7f, to_7bit(value)], 3),
                ExprKind::Slide => ([0xb0 | (channel & 0x0f), SLIDE_CC, to_7bit(value)], 3),
                ExprKind::Pitch => bend_bytes(channel, value / MPE_BEND_RANGE),
            },
            Self::ControlChange { channel, cc, value } => {
                ([0xb0 | (channel & 0x0f), cc & 0x7f, value & 0x7f], 3)
            }
            Self::PitchBend { channel, value } => bend_bytes(channel, value),
            Self::ChannelPressure { channel, value } => {
                ([0xd0 | (channel & 0x0f), to_7bit(value), 0], 2)
            }
            Self::ProgramChange { channel, program } => {
                ([0xc0 | (channel & 0x0f), program & 0x7f, 0], 2)
            }
            Self::AllNotesOff => ([0xb0, 123, 0], 3),
        }
    }

    /// Sort priority so that note-offs at the same timestamp come before note-ons
    /// (otherwise a retriggered note would be cut immediately).
    pub fn order(&self) -> u8 {
        match self {
            Self::AllNotesOff => 0,
            Self::NoteOff { .. } => 1,
            Self::ControlChange { .. }
            | Self::PitchBend { .. }
            | Self::ChannelPressure { .. }
            | Self::ProgramChange { .. } => 2,
            Self::NoteOn { .. } => 3,
            // After the note-on it applies to, so a plugin knows the note it refers to.
            Self::NoteExpr { .. } => 4,
        }
    }
}

fn to_7bit(value: f32) -> u8 {
    ((value.clamp(0.0, 1.0) * 127.0).round() as u8).min(127)
}

fn bend_bytes(channel: u8, value: f32) -> ([u8; 3], usize) {
    // The inverse of `from_bytes`, so parsed bends come back to the same 14 bits.
    let raw = ((value.clamp(-1.0, 1.0) * 8192.0).round() as i32 + 8192).clamp(0, 16383) as u16;
    (
        [
            0xe0 | (channel & 0x0f),
            (raw & 0x7f) as u8,
            (raw >> 7) as u8 & 0x7f,
        ],
        3,
    )
}

/// A timestamped MIDI message. `offset` is the sample frame within the current block.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct MidiEvent {
    pub offset: u32,
    pub message: MidiMessage,
}

impl MidiEvent {
    pub fn new(offset: u32, message: MidiMessage) -> Self {
        Self { offset, message }
    }

    pub fn sort_key(&self) -> (u32, u8) {
        (self.offset, self.message.order())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// `from_bytes` then `to_bytes`, which must reproduce the bytes.
    fn round_trip(bytes: &[u8]) -> MidiMessage {
        let m = MidiMessage::from_bytes(bytes).expect("parses");
        let (out, n) = m.to_bytes();
        assert_eq!(&out[..n], bytes, "{m:?}");
        m
    }

    #[test]
    fn every_channel_message_round_trips() {
        assert!(matches!(
            round_trip(&[0x93, 60, 100]),
            MidiMessage::NoteOn {
                channel: 3,
                key: 60,
                note_id: 0,
                ..
            }
        ));
        assert!(matches!(
            round_trip(&[0x83, 60, 7]),
            MidiMessage::NoteOff {
                channel: 3,
                key: 60,
                note_id: 0,
                ..
            }
        ));
        assert_eq!(
            round_trip(&[0xa2, 61, 127]),
            MidiMessage::NoteExpr {
                channel: 2,
                key: 61,
                note_id: 0,
                kind: ExprKind::Pressure,
                value: 1.0,
            }
        );
        assert_eq!(
            round_trip(&[0xb4, 7, 99]),
            MidiMessage::ControlChange {
                channel: 4,
                cc: 7,
                value: 99
            }
        );
        assert_eq!(
            round_trip(&[0xc5, 12]),
            MidiMessage::ProgramChange {
                channel: 5,
                program: 12
            }
        );
        assert_eq!(
            round_trip(&[0xd6, 127]),
            MidiMessage::ChannelPressure {
                channel: 6,
                value: 1.0
            }
        );
        assert!(matches!(
            round_trip(&[0xe7, 1, 64]),
            MidiMessage::PitchBend { channel: 7, .. }
        ));
    }

    #[test]
    fn expression_kinds_encode_as_their_mpe_messages() {
        let expr = |kind, value| MidiMessage::NoteExpr {
            channel: 3,
            key: 62,
            note_id: 9,
            kind,
            value,
        };
        let (bytes, n) = expr(ExprKind::Pressure, 1.0).to_bytes();
        assert_eq!(&bytes[..n], &[0xa3, 62, 127]);
        let (bytes, n) = expr(ExprKind::Slide, 1.0).to_bytes();
        assert_eq!(&bytes[..n], &[0xb3, SLIDE_CC, 127]);
        let (bytes, n) = expr(ExprKind::Pitch, 0.0).to_bytes();
        assert_eq!(&bytes[..n], &[0xe3, 0, 64]);
    }

    #[test]
    fn expression_sorts_after_the_note_on_it_follows() {
        let on = MidiMessage::NoteOn {
            channel: 0,
            key: 60,
            velocity: 1.0,
            note_id: 1,
            tuning: 0.0,
        };
        let expr = MidiMessage::NoteExpr {
            channel: 0,
            key: 60,
            note_id: 1,
            kind: ExprKind::Slide,
            value: 0.5,
        };
        assert!(on.order() < expr.order());
        assert!(MidiEvent::new(4, on).sort_key() < MidiEvent::new(4, expr).sort_key());
    }

    #[test]
    fn note_ids_are_never_zero_and_fit_a_signed_id() {
        let mut ids = NoteIds::new(NoteSpace::Device);
        let first = ids.alloc();
        assert_ne!(first, 0);
        assert!(first <= i32::MAX as u32);
        assert_ne!(first, NoteIds::new(NoteSpace::MidiInput).alloc());
        assert_ne!(first, ids.alloc());
    }

    #[test]
    fn parse_roundtrip() {
        let on = MidiMessage::from_bytes(&[0x91, 60, 127]).unwrap();
        assert_eq!(
            on,
            MidiMessage::NoteOn {
                channel: 1,
                key: 60,
                velocity: 1.0,
                note_id: 0,
                tuning: 0.0,
            }
        );
        let (bytes, n) = on.to_bytes();
        assert_eq!(&bytes[..n], &[0x91, 60, 127]);
        // Note-on with velocity 0 is a note-off.
        assert!(matches!(
            MidiMessage::from_bytes(&[0x90, 60, 0]),
            Some(MidiMessage::NoteOff { key: 60, .. })
        ));
        let bend = MidiMessage::from_bytes(&[0xe0, 0, 64]).unwrap();
        assert_eq!(
            bend,
            MidiMessage::PitchBend {
                channel: 0,
                value: 0.0
            }
        );
    }
}
