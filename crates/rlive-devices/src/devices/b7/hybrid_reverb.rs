#[derive(Clone, Copy, Default)]
struct OnePole {
    z: f32,
}

/// Four bands: pass or shelf, two peaks, pass or shelf.
#[derive(Clone)]
struct Eq {
    low: [Biquad; 8],
    low_sections: usize,
    low_pole: f32,
    peak: [Biquad; 2],
    high: [Biquad; 8],
    high_sections: usize,
    high_pole: f32,
    low_z: OnePole,
    high_z: OnePole,
}

impl Default for Eq {
    fn default() -> Self {
        Self {
            low: [Biquad::default(); 8],
            low_sections: 1,
            low_pole: 0.0,
            peak: [Biquad::default(); 2],
            high: [Biquad::default(); 8],
            high_sections: 1,
            high_pole: 0.0,
            low_z: OnePole::default(),
            high_z: OnePole::default(),
        }
    }
}

impl Eq {
    fn configure(&mut self, v: &[f64; PARAMS], sr: f32) {
        let value = |id: u32| v[id as usize] as f32;
        self.peak[0].set(
            BiquadKind::Peak,
            value(EQ_PEAK1_FREQ),
            value(EQ_PEAK1_Q),
            value(EQ_PEAK1_GAIN),
            sr,
        );
        self.peak[1].set(
            BiquadKind::Peak,
            value(EQ_PEAK2_FREQ),
            value(EQ_PEAK2_Q),
            value(EQ_PEAK2_GAIN),
            sr,
        );
        let low_pass = v[EQ_LOW_MODE as usize] >= 0.5;
        let high_pass = v[EQ_HIGH_MODE as usize] >= 0.5;
        let slope_low = (v[EQ_LOW_SLOPE as usize].round() as usize).min(PASS_SLOPE_DB.len() - 1);
        let slope_high = (v[EQ_HIGH_SLOPE as usize].round() as usize).min(PASS_SLOPE_DB.len() - 1);
        let (f_low, f_high) = (value(EQ_LOW_FREQ), value(EQ_HIGH_FREQ));
        let hp = (PASS_SLOPE_DB[slope_low] / 6.0) as usize;
        self.low_sections = hp / 2;
        self.low_pole = 0.0;
        if low_pass {
            if hp == 1 {
                self.low_pole = (-TAU * f_low / sr).exp();
            }
            for (k, f) in self.low.iter_mut().take(hp / 2).enumerate() {
                f.set(BiquadKind::HighPass, f_low, butterworth_q(hp, k), 0.0, sr);
            }
        } else {
            self.low_sections = 1;
            self.low[0].set(BiquadKind::LowShelf, f_low, 0.707, value(EQ_LOW_GAIN), sr);
        }
        let lp = (PASS_SLOPE_DB[slope_high] / 6.0) as usize;
        self.high_sections = lp / 2;
        self.high_pole = 0.0;
        if high_pass {
            if lp == 1 {
                self.high_pole = (-TAU * f_high / sr).exp();
            }
            for (k, f) in self.high.iter_mut().take(lp / 2).enumerate() {
                f.set(BiquadKind::LowPass, f_high, butterworth_q(lp, k), 0.0, sr);
            }
        } else {
            self.high_sections = 1;
            self.high[0].set(
                BiquadKind::HighShelf,
                f_high,
                0.707,
                value(EQ_HIGH_GAIN),
                sr,
            );
        }
    }

    fn reset(&mut self) {
        for f in self
            .low
            .iter_mut()
            .chain(self.peak.iter_mut())
            .chain(self.high.iter_mut())
        {
            f.reset();
        }
        self.low_z = OnePole::default();
        self.high_z = OnePole::default();
    }

    #[inline]
    fn process(&mut self, mut x: f32) -> f32 {
        if self.low_pole > 0.0 {
            // A one-pole high-pass.
            self.low_z.z = self.low_pole * self.low_z.z + (1.0 - self.low_pole) * x;
            x -= self.low_z.z;
        } else {
            for f in self.low.iter_mut().take(self.low_sections) {
                x = f.process(x);
            }
        }
        x = self.peak[0].process(x);
        x = self.peak[1].process(x);
        if self.high_pole > 0.0 {
            self.high_z.z = self.high_pole * self.high_z.z + (1.0 - self.high_pole) * x;
            x = self.high_z.z;
        } else {
            for f in self.high.iter_mut().take(self.high_sections) {
                x = f.process(x);
            }
        }
        x
    }
}

/// Q of section `k` of an `order`-pole Butterworth filter built from biquads.
fn butterworth_q(order: usize, k: usize) -> f32 {
    let angle = (2 * k + 1) as f32 * PI / (2 * order) as f32;
    1.0 / (2.0 * angle.cos())
}

#[derive(Clone, Copy, Default)]
struct Degrader {
    phase: f32,
    hold: [f32; 2],
}

impl Degrader {
    #[inline]
    fn process(&mut self, l: f32, r: f32, rate: f32, bits: f32) -> [f32; 2] {
        self.phase += rate;
        if self.phase >= 1.0 {
            self.phase -= 1.0;
            let q = 2f32.powf(bits);
            self.hold = [(l * q).round() / q, (r * q).round() / q];
        }
        self.hold
    }
}

