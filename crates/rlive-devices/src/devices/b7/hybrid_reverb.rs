const ER_GAIN: [f32; 6] = [1.0, 0.7, 0.55, 0.42, 0.3, 0.2];
const DIFFUSER_MS: [f32; 4] = [4.77, 3.59, 2.29, 1.27];
const SHIMMER_DIFFUSER_MS: [f32; 4] = [11.3, 7.7, 5.3, 3.1];
const SHIMMER_DIFFUSER_TOTAL_MS: f32 = 27.4;
/// Tank scale of Size 0 to 100.
fn size_scale(size_percent: f32) -> f32 {
    0.02 * 100f32.powf((size_percent * 0.01).clamp(0.0, 1.0))
}

impl AlgoEngine {
    fn prepare(&mut self, sample_rate: f64) {
        self.sr = sample_rate as f32;
        self.tank.prepare(sample_rate, 3.0);
        let delay = (MAX_ALGO_DELAY_MS as f64 * 0.001 * sample_rate) as usize + 8;
        let er = (sample_rate * 0.4) as usize + 8;
        for ch in 0..2 {
            self.delay[ch] = InterpDelay::new(delay);
            self.er_line[ch] = InterpDelay::new(er);
            self.diffuser[ch].prepare(sample_rate, &DIFFUSER_MS);
            self.velvet[ch].prepare(sample_rate, 0x51 + ch as u32);
            self.shimmer[ch].line = InterpDelay::new((sample_rate * 0.7) as usize + 16);
            self.shimmer[ch]
                .diffuser
                .prepare(sample_rate, &SHIMMER_DIFFUSER_MS);
            self.shimmer[ch].pitch.ring = InterpDelay::new((sample_rate * 0.1) as usize + 16);
            self.shimmer[ch].pitch.window = (sample_rate * 0.05) as f32;
        }
        self.tide_lfo.prepare(sample_rate);
        for ch in 0..2 {
            for band in 0..TIDE_BANDS {
                let hz = 120.0 * 1.8f32.powi(band as i32);
                self.tide_filter[ch][band].set(BiquadKind::BandPass, hz, TIDE_Q, 0.0, self.sr);
            }
        }
    }

    fn clear(&mut self) {
        self.tank.clear();
        for ch in 0..2 {
            self.delay[ch].clear();
            self.er_line[ch].clear();
            self.diffuser[ch].clear();
            self.velvet[ch].line.clear();
            let s = &mut self.shimmer[ch];
            s.line.clear();
            s.diffuser.clear();
            s.pitch.ring.clear();
            s.damp = 0.0;
            for f in self.tide_filter[ch].iter_mut() {
                f.reset();
            }
        }
    }

    fn configure(&mut self, v: &[f64; PARAMS]) {
        let value = |id: u32| v[id as usize] as f32;
        let flag = |id: u32| v[id as usize] >= 0.5;
        self.algo = (v[ALGORITHM as usize].round() as usize).min(PRISM);
        self.freeze = flag(FREEZE);
        self.freeze_in = flag(FREEZE_IN);
        self.delay_samples = (value(DELAY) * self.sr * 0.001).round();
        let decay = value(DECAY);
        let scale = size_scale(value(SIZE));
        let damp = value(DAMPING) * 0.01 * 0.85;
        let modulation = value(MODULATION) * 0.01;
        let mut settings = TankSettings {
            lines: 8,
            scale,
            allpass_scale: 1.0,
            diffusion: 0.5,
            t60_low: decay,
            t60_high: decay,
            xover_hz: 250.0,
            damp,
            mod_ms: modulation * 2.5,
            mod_hz: 0.6,
            freeze: self.freeze,
        };
        match self.algo {
            DARK_HALL => {
                // Shape: from small and resonant to large and diffused.
                let shape = value(SHAPE) * 0.01;
                settings.scale = (scale * (0.35 + 1.05 * shape)).min(3.0);
                settings.diffusion = 0.05 + 0.7 * shape;
                settings.xover_hz = value(BASS_X);
                settings.t60_low = decay * value(BASS_MULT);
                self.diffusion_in = 0.2 + 0.55 * shape;
            }
            QUARTZ => {
                let distance = value(DISTANCE) * 0.01;
                settings.scale = (scale * (0.5 + distance)).min(3.0);
                settings.diffusion = value(DIFFUSION) * 0.01 * 0.75;
                settings.t60_low = decay * (1.0 - value(LO_DAMP) * 0.01 * 0.9).max(0.05);
                settings.xover_hz = 250.0;
                self.er_spacing = (6.0 + 120.0 * distance) * self.sr * 0.001;
            }
            SHIMMER_ALGO => {
                self.shimmer_mix = value(SHIMMER) * 0.01;
                self.shimmer_diffusion = value(DIFFUSION) * 0.01 * 0.75;
                self.shimmer_damp = if self.freeze { 0.0 } else { damp };
                self.shimmer_mod = modulation * 2.5 * self.sr * 0.001;
                let delay_ms = 5.0 * 80f32.powf((value(SIZE) * 0.01).clamp(0.0, 1.0));
                self.shimmer_delay = (delay_ms * self.sr * 0.001).round().max(1.0);
                let loop_s = (self.shimmer_delay / self.sr) + SHIMMER_DIFFUSER_TOTAL_MS * 0.001;
                self.shimmer_gain = if self.freeze {
                    1.0
                } else {
                    10f32.powf(-3.0 * loop_s / decay.max(1e-3))
                };
                let ratio = 2f32.powf(value(PITCH) / 12.0);
                for loop_ in self.shimmer.iter_mut() {
                    loop_.pitch.set_ratio(ratio);
                }
            }
            TIDES => {
                // The manual gives Tides no Mod control.
                settings.mod_ms = 0.0;
                self.tide_amount = value(TIDE) * 0.01;
                self.wave = value(WAVE) * 0.01;
                let rate = SyncRate::from_index(v[RATE as usize]).beats();
                self.tide_lfo.set(&LfoSettings {
                    rate: LfoRate::Beats(rate),
                    phase: value(PHASE) / 360.0,
                    ..Default::default()
                });
            }
            PRISM => {
                settings.t60_low = decay * value(LOW_MULT);
                settings.t60_high = decay * value(HIGH_MULT);
                settings.xover_hz = value(XOVER);
                settings.damp = 0.0;
                settings.mod_ms = 0.0;
                let window = (3.0 + 40.0 * value(SIZE) * 0.01) * self.sr * 0.001;
                for f in self.velvet.iter_mut() {
                    f.length = window;
                }
            }
            _ => {}
        }
        self.tank.set(&settings, 0.05);
    }

    fn set_clock(&mut self, clock: &BeatClock) {
        self.tide_lfo.set_clock(clock);
    }

    fn update_tides(&mut self) {
        let [left, right] = self.tide_lfo.advance_phases(CONTROL_FRAMES);
        for (ch, phase) in [left, right].into_iter().enumerate() {
            let wrapped = phase < self.tide_last_phase[ch];
            self.tide_last_phase[ch] = phase;
            for band in 0..TIDE_BANDS {
                let p = (phase + band as f32 / TIDE_BANDS as f32).fract();
                if wrapped && band == 0 {
                    for hold in self.tide_hold[ch].iter_mut() {
                        *hold = self.tide_rng.bipolar();
                    }
                }
                let sine = (TAU * p).sin();
                let v = if self.wave < 0.5 {
                    let w = self.wave * 2.0;
                    self.tide_hold[ch][band] * (1.0 - w) + sine * w
                } else {
                    let w = (self.wave - 0.5) * 2.0;
                    let square = if sine >= 0.0 { 1.0 } else { -1.0 };
                    sine * (1.0 - w) + square * w
                };
                self.tide_level[ch][band] = 0.5 + 0.5 * v;
            }
        }
    }

    #[inline]
    fn shimmer_channel(&mut self, ch: usize, x: f32) -> f32 {
        let diffusion = self.shimmer_diffusion;
        let (mix, gain, delay, depth, damp) = (
            self.shimmer_mix,
            self.shimmer_gain,
            self.shimmer_delay,
            self.shimmer_mod,
            self.shimmer_damp,
        );
        let sr = self.sr;
        let loop_ = &mut self.shimmer[ch];
        loop_.mod_phase = (loop_.mod_phase + 0.4 / sr).rem_euclid(1.0);
        let modulation = if depth > 0.0 {
            depth * (1.0 + (TAU * loop_.mod_phase).sin())
        } else {
            0.0
        };
        let y = loop_
            .line
            .read(delay - 1.0 + modulation, Interpolation::Linear);
        let diffused = loop_.diffuser.process(y, diffusion);
        let pitched = loop_.pitch.process(diffused);
        let mut feedback = diffused * (1.0 - mix) + pitched * mix;
        if damp > 0.0 {
            loop_.damp += (1.0 - damp) * (feedback - loop_.damp);
            feedback = loop_.damp;
        }
        loop_.line.write(sanitize(soft_limit(x + feedback * gain)));
        y
    }

    /// One stereo frame through the current algorithm.
    #[inline]
    fn process(&mut self, in_l: f32, in_r: f32) -> [f32; 2] {
        let live = !self.freeze || self.freeze_in;
        let (dry_l, dry_r) = if live { (in_l, in_r) } else { (0.0, 0.0) };
        let delayed = [
            {
                self.delay[0].write(dry_l);
                self.delay[0].read(self.delay_samples, Interpolation::Linear)
            },
            {
                self.delay[1].write(dry_r);
                self.delay[1].read(self.delay_samples, Interpolation::Linear)
            },
        ];
        match self.algo {
            QUARTZ => {
                let mut er = [0.0f32; 2];
                for ch in 0..2 {
                    self.er_line[ch].write(delayed[ch]);
                    for (k, gain) in ER_GAIN.iter().enumerate() {
                        let at = self.er_spacing * (1.0 + k as f32 * 1.27);
                        er[ch] += gain * self.er_line[ch].read(at, Interpolation::Linear);
                    }
                }
                let out = self.tank.process(er[0] * 0.5, er[1] * 0.5);
                [er[0] * 0.45 + out[0], er[1] * 0.45 + out[1]]
            }
            SHIMMER_ALGO => [
                self.shimmer_channel(0, delayed[0]),
                self.shimmer_channel(1, delayed[1]),
            ],
            TIDES => {
                self.frames += 1;
                if self.frames >= CONTROL_FRAMES {
                    self.frames = 0;
                    self.update_tides();
                }
                let mut out = self.tank.process(delayed[0], delayed[1]);
                if self.tide_amount > 0.0 {
                    for (ch, sample) in out.iter_mut().enumerate() {
                        let mut ripple = 0.0;
                        for (filter, level) in
                            self.tide_filter[ch].iter_mut().zip(self.tide_level[ch])
                        {
                            ripple += filter.process(*sample) * level;
                        }
                        *sample -= ripple * self.tide_amount;
                    }
                }
                out
            }
            PRISM => {
                let l = self.velvet[0].process(delayed[0]);
                let r = self.velvet[1].process(delayed[1]);
                self.tank.process(l, r)
            }
            _ => {
                let l = self.diffuser[0].process(delayed[0], self.diffusion_in);
                let r = self.diffuser[1].process(delayed[1], self.diffusion_in);
                self.tank.process(l, r)
            }
        }
    }
}

