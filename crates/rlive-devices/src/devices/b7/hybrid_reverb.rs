// ---------------------------------------------------------------------- Convolution engine

/// What a build reads from: a generated response or the user's file.
#[derive(Clone, Copy)]
struct Source<'a> {
    left: &'a [f32],
    right: &'a [f32],
    gain: f32,
    /// Source frames per output frame.
    step: f32,
}

impl Source<'_> {
    fn frames(&self) -> usize {
        self.left.len().min(self.right.len())
    }
}

/// The current state of the shape controls.
#[derive(Clone, Copy, PartialEq, Debug)]
struct Shape {
    attack: f32,
    decay: Option<f32>,
    frames: usize,
    truncated: bool,
}

#[inline]
fn shaped_sample(source: Source<'_>, channel: usize, shape: Shape, index: usize) -> f32 {
    let (left, right) = (source.left, source.right);
    let data = if channel == 0 { left } else { right };
    let at = index as f32 * source.step;
    let whole = at as usize;
    let t = at - whole as f32;
    let y = data.get(whole).copied().unwrap_or(0.0);
    let v = y + (data.get(whole + 1).copied().unwrap_or(0.0) - y) * t;
    let mut env = source.gain;
    if shape.attack > 0.0 {
        env *= (index as f32 / shape.attack).min(1.0);
    }
    if let Some(decay) = shape.decay {
        env *= (-6.907_755 * index as f32 / decay.max(1.0)).exp();
    }
    if shape.truncated {
        let from_end = shape.frames.saturating_sub(index).min(PARTITION) as f32;
        env *= from_end / PARTITION as f32;
    }
    v * env
}

/// A response being built on the audio thread.
#[derive(Clone, Copy, Debug)]
struct Build {
    partitions: usize,
    channel: usize,
    partition: usize,
}

struct ConvolutionEngine {
    sr: f32,
    max_partitions: usize,
    /// Two pairs of convolvers: one playing, one for the next response.
    convolvers: [[Convolver; 2]; 2],
    /// The standby pair's responses while they're being rebuilt.
    spare: [Option<Arc<ConvolverIr>>; 2],
    active: usize,
    /// Progress of a crossfade from the active pair to the other, 0..1; 1 means none.
    fade: f32,
    fade_step: f32,
    build: Option<Build>,
    credits: f32,
    credit_per_frame: f32,
    fft: Fft,
    time: Vec<f32>,
    chunk: Vec<f32>,
    /// A control moved since the last build started.
    stale: bool,
    summary: [f32; IR_VIEW_LEN],
}

impl ConvolutionEngine {
    fn new(sample_rate: f64) -> Self {
        let sr = sample_rate as f32;
        let frames = (MAX_IR_SECONDS * sample_rate) as usize;
        let max_partitions = frames.div_ceil(PARTITION).max(1);
        let make = || {
            [
                Convolver::new(PARTITION, max_partitions),
                Convolver::new(PARTITION, max_partitions),
            ]
        };
        let mut convolvers = [make(), make()];
        // The pair that starts out playing has a silent response of its own, so the spare can be
        // rebuilt independently of it from the start.
        for c in convolvers[0].iter_mut() {
            c.set_ir(Arc::new(ConvolverIr::silent(PARTITION, max_partitions)));
        }
        Self {
            sr,
            max_partitions,
            convolvers,
            spare: [
                Some(Arc::new(ConvolverIr::silent(PARTITION, max_partitions))),
                Some(Arc::new(ConvolverIr::silent(PARTITION, max_partitions))),
            ],
            active: 0,
            fade: 1.0,
            fade_step: 1.0 / (CROSSFADE_SECONDS * sr).max(1.0),
            build: None,
            credits: 0.0,
            credit_per_frame: 0.0,
            fft: Fft::new(PARTITION * 2),
            time: vec![0.0; PARTITION * 2],
            chunk: vec![0.0; PARTITION],
            stale: true,
            summary: [0.0; IR_VIEW_LEN],
        }
    }

    fn clear(&mut self) {
        if self.fade < 1.0 {
            // A crossfade cut short still ends on the new response, and hands the old one back.
            self.finish_fade();
            self.fade = 1.0;
        }
        for pair in self.convolvers.iter_mut() {
            for c in pair.iter_mut() {
                c.reset();
            }
        }
    }

    fn standby(&self) -> usize {
        1 - self.active
    }

    /// Starts over on the current selection. `source`, `shape` and `partitions` describe it.
    fn begin(&mut self, shape: Shape) {
        let partitions = shape
            .frames
            .div_ceil(PARTITION)
            .clamp(1, self.max_partitions);
        for ch in 0..2 {
            let ir = self.spare[ch]
                .as_mut()
                .and_then(Arc::get_mut)
                .expect("the spare response is owned here while building");
            ir.set_partitions(partitions);
        }
        self.build = Some(Build {
            partitions,
            channel: 0,
            partition: 0,
        });
        self.credits = 0.0;
        self.credit_per_frame = (partitions * 2) as f32 / (BUILD_SECONDS * self.sr).max(1.0);
        self.stale = false;
    }

    /// Writes `count` more partitions. Returns whether the build is done.
    fn advance(&mut self, source: Source<'_>, shape: Shape, mut count: usize) -> bool {
        let Some(mut build) = self.build else {
            return true;
        };
        while count > 0 && build.channel < 2 {
            let start = build.partition * PARTITION;
            for (i, s) in self.chunk.iter_mut().enumerate() {
                *s = if start + i < shape.frames {
                    shaped_sample(source, build.channel, shape, start + i)
                } else {
                    0.0
                };
            }
            let ir = self.spare[build.channel]
                .as_mut()
                .and_then(Arc::get_mut)
                .expect("the spare response is owned here while building");
            ir.write_partition(build.partition, &self.chunk, &mut self.fft, &mut self.time);
            build.partition += 1;
            if build.partition == build.partitions {
                build.partition = 0;
                build.channel += 1;
            }
            count -= 1;
        }
        let done = build.channel >= 2;
        self.build = if done { None } else { Some(build) };
        done
    }

    /// Puts the finished response on the standby pair and starts the crossfade to it.
    fn commit(&mut self) {
        let next = self.standby();
        for ch in 0..2 {
            let ir = self.spare[ch].take().expect("a built response");
            // The standby convolver is empty, so nothing comes back; if this ever fails we keep
            // the response rather than free it on the audio thread.
            self.spare[ch] = self.convolvers[next][ch].set_ir(ir);
        }
        self.fade = 0.0;
    }

    /// Swaps the pairs once a crossfade ends and reclaims the old responses for the next build.
    fn finish_fade(&mut self) {
        let old = self.active;
        self.active = self.standby();
        for ch in 0..2 {
            self.convolvers[old][ch].reset();
            self.spare[ch] = self.convolvers[old][ch].take_ir();
        }
    }

    /// Applies an already-known selection without any audio running.
    fn install_now(&mut self, source: Source<'_>, shape: Shape) {
        self.begin(shape);
        let total = shape
            .frames
            .div_ceil(PARTITION)
            .clamp(1, self.max_partitions)
            * 2;
        self.advance(source, shape, total);
        // No sound is playing: skip the crossfade and go straight to the new response.
        let next = self.standby();
        for ch in 0..2 {
            let ir = self.spare[ch].take().expect("a built response");
            self.spare[ch] = self.convolvers[next][ch].set_ir(ir);
        }
        self.fade = 1.0;
        self.active = next;
        // The old pair's responses become the spare for the next change.
        for ch in 0..2 {
            let other = 1 - next;
            self.spare[ch] = self.convolvers[other][ch]
                .take_ir()
                .or(self.spare[ch].take());
        }
        self.build = None;
        self.update_summary(source, shape);
    }

    /// Advances any build and crossfade by `frames` of progress.
    fn step(&mut self, source: Source<'_>, shape: Shape, frames: usize) {
        if self.fade >= 1.0 && self.build.is_none() && self.stale {
            self.begin(shape);
        }
        if self.build.is_some() {
            if self.stale {
                self.begin(shape);
            }
            self.credits += frames as f32 * self.credit_per_frame;
            let count = self.credits as usize;
            self.credits -= count as f32;
            if self.advance(source, shape, count) && !self.stale {
                self.update_summary(source, shape);
                self.commit();
            }
        }
    }

    fn update_summary(&mut self, source: Source<'_>, shape: Shape) {
        const POINTS: usize = IR_VIEW_LEN - 1;
        let total = shape.frames.max(1);
        let spread = (total / POINTS).max(1);
        let (mut peak, mut filled) = (1e-9f32, [0.0f32; POINTS]);
        for (p, out) in filled.iter_mut().enumerate() {
            let at = p * total / POINTS;
            let mut max = 0.0f32;
            for k in 0..spread.min(8) {
                let i = at + k * spread / 8;
                let x = shaped_sample(source, 0, shape, i).abs()
                    + shaped_sample(source, 1, shape, i).abs();
                max = max.max(x);
            }
            *out = max;
            peak = peak.max(max);
        }
        self.summary[0] = 1.0;
        for (o, x) in self.summary[1..].iter_mut().zip(filled) {
            *o = x / peak;
        }
    }

    /// Runs `frames` of input through the pair playing, and through the next pair too during a
    /// crossfade, adding the result to `out`.
    fn process(
        &mut self,
        input: [&[f32]; 2],
        out: &mut [Vec<f32>; 2],
        scratch: &mut [Vec<f32>; 2],
    ) {
        let frames = input[0].len();
        if self.fade >= 1.0 {
            for ch in 0..2 {
                self.convolvers[self.active][ch].process(input[ch], &mut out[ch][..frames]);
            }
            return;
        }
        let next = self.standby();
        for ch in 0..2 {
            self.convolvers[self.active][ch].process(input[ch], &mut out[ch][..frames]);
            self.convolvers[next][ch].process(input[ch], &mut scratch[ch][..frames]);
        }
        let mut fade = self.fade;
        for i in 0..frames {
            let (old_gain, new_gain) = ((FRAC_PI_2 * fade).cos(), (FRAC_PI_2 * fade).sin());
            out[0][i] = out[0][i] * old_gain + scratch[0][i] * new_gain;
            out[1][i] = out[1][i] * old_gain + scratch[1][i] * new_gain;
            fade = (fade + self.fade_step).min(1.0);
        }
        self.fade = fade;
        if self.fade >= 1.0 {
            self.finish_fade();
        }
    }
}

