//! Hybrid Reverb: a partitioned convolution engine and five algorithms, in series or parallel,
//! with EQ and a vintage degrader (manual pages 619-625).
//!
//! The manual gives the routing modes, the ten IR categories, the five algorithm names and what
//! each control means, the 6 to 96 dB/octave pass-filter slopes, Stereo above 100%, Bass Mono's
//! 180 Hz, Phase's 180 degree point and the four vintage presets. It gives no ranges for times,
//! sizes, damping or the shape of any modulation, and doesn't describe the algorithms beyond a
//! sentence or two: the constants and structures here are ours.
//!
